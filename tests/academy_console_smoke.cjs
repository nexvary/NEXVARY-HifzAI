'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(require.resolve('playwright',{paths:[process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES || path.resolve('academy/test/node_modules')]}));
(async()=>{
  const out=process.env.HIFZ_CONSOLE_PROOF;
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1000,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',dialog=>dialog.accept());
  const login=async name=>{
    await page.getByLabel('اسم الحساب',{exact:true}).fill(name);
    await page.getByLabel('كلمة المرور',{exact:true}).fill('synthetic-console-password-2026');
    await page.getByRole('button',{name:'دخول',exact:true}).click();
    await page.locator('#workspace').waitFor({state:'visible'});
  };
  const logout=async()=>{await page.getByRole('button',{name:'خروج',exact:true}).click();await page.locator('#login').waitFor({state:'visible'});};
  const shot=async name=>{await page.screenshot({path:path.join(out,name+'.png'),fullPage:true});};
  try{
    await page.goto(process.env.HIFZ_CONSOLE_URL);
    assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
    await shot('01-login');
    await login('teacher');
    await page.getByLabel('اسم العرض',{exact:true}).fill('معلم تجريبي — ليس مؤهلًا فعليًا');
    await page.getByLabel('وصف المؤهل وطريقة التحقق منه').fill('بيانات اصطناعية لا تمثل شهادة حقيقية');
    await page.getByRole('button',{name:'تقديم الملف للمراجعة',exact:true}).click();
    await page.getByText('الحالة: بانتظار المراجعة',{exact:true}).waitFor();
    await logout();
    await login('administrator');
    await page.getByLabel('مرجع تحقق بشري خاص — دون أسرار أو أرقام هوية').fill('اختبار آلي اصطناعي للمسار؛ لا موافقة بشرية حقيقية');
    await page.getByLabel('أقر بأنني راجعت الأدلة البشرية المخوّل بفحصها').check();
    await page.getByRole('button',{name:'توثيق قرار المراجعة',exact:true}).click();
    await page.getByText('الحالة: مقبول داخليًا',{exact:true}).waitFor();
    await shot('02-admin-review-synthetic');
    await page.getByRole('button',{name:'الحسابات',exact:true}).click();
    await page.getByRole('heading',{name:'إدارة حسابات البالغين'}).waitFor();
    await shot('03-admin-accounts');
    await logout();
    await login('teacher');
    await page.getByRole('button',{name:'مواعيدي',exact:true}).click();
    const start=new Date(Date.now()+3600000),end=new Date(start.getTime()+1800000);
    const local=d=>new Date(d.getTime()-d.getTimezoneOffset()*60000).toISOString().slice(0,16);
    await page.getByLabel('البداية بتوقيت جهازك').fill(local(start));
    await page.getByLabel('النهاية بتوقيت جهازك').fill(local(end));
    await page.getByRole('button',{name:'إضافة وقت متاح',exact:true}).click();
    await page.getByRole('button',{name:'حذف الموعد',exact:true}).waitFor();
    await shot('04-teacher-availability');
    await logout();
    await login('guardian');
    await page.getByLabel('اسم مستعار — دون بيانات هوية').fill('طالب اصطناعي');
    await page.getByLabel('أنا ولي أمر بالغ مخوّل بإدارة هذا الملف').check();
    await page.getByLabel('أوافق على حفظ هذا الملف والملاحظات داخل بيئة الفحص الخاصة').check();
    await page.getByRole('button',{name:'إضافة طالب باسم مستعار',exact:true}).click();
    await page.getByRole('button',{name:'خطة الطالب وجلساته',exact:true}).click();
    await page.getByRole('button',{name:'ربط بمعلم وعرض مواعيده',exact:true}).click();
    await page.getByRole('button',{name:'حجز الفترة المختارة',exact:true}).click();
    await page.getByText('الحالة: محجوزة',{exact:true}).waitFor();
    await shot('05-guardian-booking');
    await page.getByLabel('وصف المشكلة').fill('بلاغ اصطناعي لفحص الخصوصية والمعالجة');
    await page.getByRole('button',{name:'تقديم بلاغ خاص',exact:true}).click();
    await page.getByRole('button',{name:'البلاغات',exact:true}).click();
    await page.getByText('بلاغ اصطناعي لفحص الخصوصية والمعالجة',{exact:true}).waitFor();
    await logout();
    await login('teacher');
    await page.getByRole('button',{name:'طلابي',exact:true}).click();
    await page.getByRole('button',{name:'خطة الطالب وجلساته',exact:true}).click();
    await page.getByLabel('رقم السورة',{exact:true}).fill('1');
    await page.getByLabel('من الآية',{exact:true}).fill('1');
    await page.getByLabel('إلى الآية',{exact:true}).fill('7');
    await page.getByLabel('موعد المراجعة',{exact:true}).fill(local(new Date(Date.now()+86400000)));
    await page.getByLabel('تعليمات المعلم',{exact:true}).fill('خطة اصطناعية لا تقييم دقة للتعلم');
    await page.getByRole('button',{name:'تعيين خطة مراجعة',exact:true}).click();
    await page.getByRole('heading',{name:'سورة 1 • الآيات 1–7',exact:true}).waitFor();
    await shot('06-teacher-plan');
    await logout();
    await login('guardian');
    await page.getByRole('button',{name:'خطة الطالب وجلساته',exact:true}).click();
    await page.getByLabel('النتيجة',{exact:true}).selectOption('recalled');
    await page.getByRole('button',{name:'حفظ المتابعة البشرية',exact:true}).click();
    await page.getByText('تقييم ولي أمر ذاتي • استرجع •',{exact:true}).waitFor();
    await page.setViewportSize({width:390,height:844});
    await shot('07-guardian-plan-mobile');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    const downloaded=page.waitForEvent('download',{timeout:5000});
    await page.getByRole('button',{name:'تنزيل ملف هذا الطالب',exact:true}).click();
    const download=await downloaded;
    assert.equal(download.suggestedFilename(),'student-private-export.json');
    const storage=await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length,password:document.getElementById('login-password').value}));
    assert.deepEqual(storage,{local:0,session:0,password:''});
    await logout();
    await login('administrator');
    await page.getByRole('button',{name:'البلاغات',exact:true}).click();
    await page.getByLabel('نتيجة معالجة البلاغ').fill('معالجة اختبار اصطناعي فقط');
    await page.getByRole('button',{name:'توثيق المعالجة البشرية',exact:true}).click();
    await page.getByRole('heading',{name:'بلاغ تمت معالجته',exact:true}).waitFor();
    await shot('08-admin-complaint-mobile');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,'browser-result.json'),JSON.stringify({successful:true,scope:'Synthetic private academy WEB console; NOT Android screenshots or teacher approval',screenshots:8,browserVersion:browser.version(),pageErrors:errors,flows:['teacher submission','admin review synthetic fixture','account directory','teacher availability','guardian consent and booking','private complaint','assigned revision plan','guardian self-report','private export','mobile width','memory-only session']},null,2));
  }catch(error){
    await shot('FAILED-diagnostic');
    fs.writeFileSync(path.join(out,'browser-failure.json'),JSON.stringify({successful:false,
      scope:'Synthetic web console failure diagnostic, not acceptance evidence',error:String(error)},null,2));
    throw error;
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
